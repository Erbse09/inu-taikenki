#!/usr/bin/env python3
"""Build the per-row source-check ledger (CSV + src/review-source-ledger.ts).

Inputs (all produced during the 2026-10-17 audit, see README.md):
  reviews.json   rows read from the live read-only API (1,595 rows)
  cands.json / cands2.json  candidate blocks found in the cached source pages
  order2.json / order3.json row order of the second / third reading batches
  kinds2.json    how each row of cands2.json was handled (read / N_lowscore / N_nooverlap / U_notext)
  manual.txt     the verdicts written while reading (token per row index, later lines override earlier ones)
Token grammar: V1/V2 (matching block = candidate 1/2 of that row), V=<idx>.<n> (block lives in another row's candidates),
               V@<page> (Rakuten list page number), P*/C* likewise, N, U.
"""
import csv, json, re, sys, collections, os
S = sys.argv[1]            # directory with the inputs
OUT = sys.argv[2]          # repository root
rows = json.load(open(f"{S}/live/reviews.json"))
byid = {r["id"]: r for r in rows}
c1 = json.load(open(f"{S}/cands.json"))
c2 = {o["id"]: o for o in json.load(open(f"{S}/cands2.json"))}
kinds = json.load(open(f"{S}/kinds2.json"))
order2 = json.load(open(f"{S}/order2.json"))
order3 = json.load(open(f"{S}/order3.json"))

entries = [(x["id"], x["cands"]) for x in c1]
entries += [(i, c2[i]["cands"]) for i in order2]
entries += [(i, c2[i]["cands"]) for i in order3]

verdict = {}
for line in open(f"{S}/manual.txt"):
    for m in re.finditer(r"(\d+):(\S+)", line):
        verdict[int(m.group(1))] = m.group(2)

def page_url(source_url, page):
    m = re.match(r"(https://review\.rakuten\.co\.jp/(?:review/)?item/1/[^/]+/)(\d+)\.(\d+)/?$", source_url)
    return f"{m.group(1)}{page}.{m.group(3)}/" if m else source_url

ledger = {}
for idx, (rid, cands) in enumerate(entries):
    tok = verdict[idx]
    st = tok[0]
    url = ""
    m = re.match(r"[VPC](\d)$", tok)
    if m and cands:
        url = cands[int(m.group(1)) - 1]["url"]
    m = re.match(r"[VPC]=(\d+)\.(\d)$", tok)
    if m:
        url = entries[int(m.group(1))][1][int(m.group(2)) - 1]["url"]
    m = re.match(r"[VPC]@(\d+)$", tok)
    if m:
        url = page_url(byid[rid]["source_url"], int(m.group(1)))
    ledger[rid] = (st, url, "manual", tok)

for sid, k in kinds.items():
    rid = int(sid)
    if rid in ledger:
        continue
    if k == "N_nooverlap":
        ledger[rid] = ("N", "", "auto", "no-keyword-overlap")
    elif k == "U_notext":
        ledger[rid] = ("U", "", "auto", "no-page-text")
    else:
        raise SystemExit(f"row {rid} ({k}) has no verdict")

ext = [r for r in rows if r["source_type"] != "existing_article_summary"]
missing = [r["id"] for r in ext if r["id"] not in ledger]
assert not missing, missing
for rid, (st, url, *_ ) in ledger.items():
    if st == "V":
        assert url.startswith("https://"), (rid, url)

os.makedirs(f"{OUT}/audit/review-source-20261017", exist_ok=True)
with open(f"{OUT}/audit/review-source-20261017/ledger.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["id", "product_id", "category", "status", "method", "page_url", "source_url", "token"])
    for r in sorted(ext, key=lambda r: r["id"]):
        st, url, method, tok = ledger[r["id"]]
        w.writerow([r["id"], r["product_id"], r["category"], st, method, url, r["source_url"], tok])

urls = sorted({v[1] for v in ledger.values() if v[0] == "V"})
uidx = {u: i for i, u in enumerate(urls)}
with open(f"{OUT}/src/review-source-ledger.ts", "w") as f:
    f.write("// GENERATED by audit/review-source-20261017/build_ledger.py from the 2026-10-17 manual source audit. Do not edit by hand.\n")
    f.write("// status: V=確認済み（確認先の一覧で対応する投稿を確認）／P=部分一致／N=見つからず／U=確認不能／C=対応すると思われる投稿は猫の飼い主によるもの\n")
    f.write("// A row that is not listed here has not been checked at all.\n")
    f.write('export const LEDGER_DATE = "2026-10-17";\n')
    f.write("export type LedgerStatus = \"V\" | \"P\" | \"N\" | \"U\" | \"C\";\n")
    f.write("export const LEDGER_URLS: string[] = " + json.dumps(urls, ensure_ascii=False, indent=0) + ";\n")
    f.write("// [status, index into LEDGER_URLS (V only)]\n")
    f.write("export const LEDGER: Record<number, [LedgerStatus, number?]> = {\n")
    for rid in sorted(ledger):
        st, url, *_ = ledger[rid]
        f.write(f"  {rid}: [\"{st}\"" + (f", {uidx[url]}" if st == "V" else "") + "],\n")
    f.write("};\n")

cnt = collections.Counter(v[0] for v in ledger.values())
mc = collections.Counter((v[0], v[2]) for v in ledger.values())
print("rows", len(ledger), dict(cnt)); print(dict(mc)); print("urls", len(urls))
